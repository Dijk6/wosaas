-- 订单信息表（参考 carsaas order_info 结构，字段按通用打车订单场景整理）
CREATE TABLE IF NOT EXISTS `order_info` (
    `id`                     BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '自增id',
    `order_no`               VARCHAR(64)     NOT NULL                COMMENT '订单编号',
    `channel_order_no`       VARCHAR(64)     NOT NULL DEFAULT ''     COMMENT '外部渠道订单号',
    `order_status`           TINYINT UNSIGNED NOT NULL DEFAULT 0     COMMENT '订单状态',
    `sp_id`                  VARCHAR(64)     NOT NULL DEFAULT ''     COMMENT '运力id',
    `cp_id`                  BIGINT          NOT NULL DEFAULT 0      COMMENT '城市合作方',
    `agent_id`               BIGINT          NOT NULL DEFAULT 0      COMMENT 'agent编号',
    `fleet_id`               BIGINT          NOT NULL DEFAULT 0      COMMENT '车队编号',
    `channel_partner_id`     INT             NOT NULL DEFAULT 0      COMMENT '外部渠道id',
    `channel_user_id`        VARCHAR(64)     NOT NULL DEFAULT ''     COMMENT '外部渠道用户标识',
    `mobile`                 VARCHAR(32)     NOT NULL DEFAULT ''     COMMENT '乘客手机号',
    `create_mobile`          VARCHAR(32)     NOT NULL DEFAULT ''     COMMENT '发单人手机号',
    `total_price`            INT UNSIGNED    NOT NULL DEFAULT 0      COMMENT '订单金额(分)',
    `pay_price`              INT UNSIGNED    NOT NULL DEFAULT 0      COMMENT '应付金额(分)',
    `channel_pay_price`      INT UNSIGNED    NOT NULL DEFAULT 0      COMMENT '外部渠道实付金额(分)',
    `driver_total_price`     INT UNSIGNED    NOT NULL DEFAULT 0      COMMENT '司机订单金额(分)',
    `start_place`            VARCHAR(255)    NOT NULL DEFAULT ''     COMMENT '出发地点',
    `start_address`          VARCHAR(512)    NOT NULL DEFAULT ''     COMMENT '出发地址',
    `start_city_id`          INT             NOT NULL DEFAULT 0      COMMENT '出发城市id',
    `end_place`              VARCHAR(255)    NOT NULL DEFAULT ''     COMMENT '到达地点',
    `end_address`            VARCHAR(512)    NOT NULL DEFAULT ''     COMMENT '到达地址',
    `end_city_id`            INT             NOT NULL DEFAULT 0      COMMENT '到达城市id',
    `start_geo`              VARCHAR(64)     NOT NULL DEFAULT ''     COMMENT '出发地经纬度',
    `end_geo`                VARCHAR(64)     NOT NULL DEFAULT ''     COMMENT '到达地经纬度',
    `driver_client_version`  VARCHAR(64)     NOT NULL DEFAULT ''     COMMENT '司机端版本号',
    `driver_device`          TINYINT         NOT NULL DEFAULT 0      COMMENT '司机端设备类型 1ios 2安卓',
    `driver_cuid`            VARCHAR(128)    NOT NULL DEFAULT ''     COMMENT '司机端设备cuid',
    `driver_uid`             VARCHAR(64)     NOT NULL DEFAULT ''     COMMENT '司机表外显id',
    `driver_mobile`          VARCHAR(32)     NOT NULL DEFAULT ''     COMMENT '司机手机号',
    `vehicle_uid`            VARCHAR(64)     NOT NULL DEFAULT ''     COMMENT '车辆id',
    `vehicle_number`         VARCHAR(32)     NOT NULL DEFAULT ''     COMMENT '车牌号',
    `car_type`               INT UNSIGNED    NOT NULL DEFAULT 0      COMMENT '车型',
    `cancel_type`            TINYINT UNSIGNED NOT NULL DEFAULT 0     COMMENT '取消类型',
    `pre_pay`                TINYINT UNSIGNED NOT NULL DEFAULT 3     COMMENT '垫付状态 3正常单 1垫付单 2垫付后乘客支付',
    `status`                 TINYINT UNSIGNED NOT NULL DEFAULT 1     COMMENT '订单删除状态 1正常 2删除',
    `start_time`             BIGINT          NOT NULL DEFAULT 0      COMMENT '预约出发时间',
    `confirm_time`           BIGINT          NOT NULL DEFAULT 0      COMMENT '接单时间',
    `pickup_time`            BIGINT          NOT NULL DEFAULT 0      COMMENT '出发接乘客时间',
    `arrive_time`            BIGINT          NOT NULL DEFAULT 0      COMMENT '到达上车点时间',
    `receive_time`           BIGINT          NOT NULL DEFAULT 0      COMMENT '行程开始时间',
    `delivery_time`          BIGINT          NOT NULL DEFAULT 0      COMMENT '行程结束时间',
    `bill_time`              BIGINT          NOT NULL DEFAULT 0      COMMENT '账单时间',
    `pay_time`               BIGINT          NOT NULL DEFAULT 0      COMMENT '支付时间',
    `create_time`            BIGINT          NOT NULL DEFAULT 0      COMMENT '创建时间',
    `update_time`            BIGINT          NOT NULL DEFAULT 0      COMMENT '更新时间',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_order_no` (`order_no`),
    KEY `idx_mobile` (`mobile`),
    KEY `idx_driver_uid` (`driver_uid`),
    KEY `idx_status_create_time` (`status`, `create_time`),
    KEY `idx_city_create_time` (`start_city_id`, `create_time`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='订单信息表';

