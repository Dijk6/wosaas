-- 导出任务表（MySQL）
CREATE TABLE IF NOT EXISTS `export_task` (
    `id`                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    `created_at`        DATETIME(3)     DEFAULT NULL,
    `updated_at`        DATETIME(3)     DEFAULT NULL,
    `task_id`           VARCHAR(64)     NOT NULL,
    `sp_id`             VARCHAR(64)     NOT NULL DEFAULT '',
    `cp_id`             BIGINT          NOT NULL DEFAULT 0,
    `src_page`          VARCHAR(64)     NOT NULL DEFAULT '',
    `sql_content`       TEXT            NOT NULL,
    `sql_type`          TINYINT         NOT NULL DEFAULT 1,
    `table_name`        VARCHAR(128)    NOT NULL DEFAULT '',
    `columns_name`      TEXT            NOT NULL,
    `database_name`     VARCHAR(64)     NOT NULL DEFAULT '',
    `status`            TINYINT         NOT NULL DEFAULT 1,
    `file_size`         BIGINT          NOT NULL DEFAULT 0,
    `sql_count`         BIGINT          NOT NULL DEFAULT 0,
    `file_url`          VARCHAR(512)    NOT NULL DEFAULT '',
    `fail_reason`      VARCHAR(512)    NOT NULL DEFAULT '',
    `creator_user_id`   VARCHAR(64)     NOT NULL DEFAULT '',
    `creator_user_name` VARCHAR(64)     NOT NULL DEFAULT '',
    `extra_info`        TEXT,
    `finish_time`       BIGINT          NOT NULL DEFAULT 0,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_task_id` (`task_id`),
    KEY `idx_status` (`status`),
    KEY `idx_src_page` (`src_page`),
    KEY `idx_sp_id` (`sp_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
